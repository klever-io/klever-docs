/**
 * Generates the gas cost tables on /smart-contracts/reference/gas from a node
 * gas schedule (`gasScheduleV1.yaml`).
 *
 * Usage:
 *   curl -sS https://backup.mainnet.klever.org/config.mainnet.<N>.tar.gz | tar -xz -C /some/empty/dir
 *   pnpm run gen:gas-tables -- /some/empty/dir/config/gasScheduleV1.yaml <N> <YYYY-MM-DD>
 *
 * <N> is the mainnet config package number and the date is the day the values
 * were read. The script rewrites everything between the GAS-TABLES markers in
 * the page and leaves the rest of the page alone.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import * as prettier from 'prettier'

const PAGE = join(
  __dirname,
  '..',
  'app',
  'smart-contracts',
  'reference',
  'gas',
  'page.mdx',
)
const BEGIN =
  '{/* BEGIN GAS-TABLES: generated by src/scripts/generate-gas-tables.ts, do not edit by hand */}'
const END = '{/* END GAS-TABLES */}'

type Schedule = Map<string, Map<string, number>>

/** The gas schedule is a flat two-level YAML map: `Section:` then `  Name: integer`. */
export function parseSchedule(text: string): Schedule {
  const schedule: Schedule = new Map()
  let section: Map<string, number> | undefined
  text.split(/\r?\n/).forEach((raw, i) => {
    const line = raw.replace(/#.*$/, '').trimEnd()
    if (line.trim() === '') return
    const top = /^([A-Za-z0-9]+):$/.exec(line)
    if (top) {
      section = new Map()
      schedule.set(top[1], section)
      return
    }
    const entry = /^\s+([A-Za-z0-9]+):\s*(-?\d+)$/.exec(line)
    if (!entry || !section) {
      throw new Error(`line ${i + 1}: unexpected content "${raw}"`)
    }
    section.set(entry[1], Number(entry[2]))
  })
  return schedule
}

const fmt = (n: number) => n.toLocaleString('en-US')

function table(headers: string[], rows: string[][]): string {
  const head = `| ${headers.join(' | ')} |`
  const sep = `| ${headers.map(() => '---').join(' | ')} |`
  return [head, sep, ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n')
}

function section(schedule: Schedule, name: string): Map<string, number> {
  const s = schedule.get(name)
  if (!s) throw new Error(`gas schedule has no ${name} section`)
  return s
}

/** One-line meanings for the entries whose name does not say enough. */
const MEANINGS: Record<string, string> = {
  // BaseOperationCost
  StorePerByte:
    'Per byte added to contract storage: a new value, or the bytes a value grows by',
  ReleasePerByte: 'Per byte a storage value shrinks by. Not charged today',
  DataCopyPerByte:
    'Per byte copied between the VM and contract memory: arguments, storage keys and values, buffers',
  PersistPerByte:
    'Per byte of a storage value that is overwritten, and of log and return data',
  CompilePerByte: 'Per byte of contract code, on deploy and upgrade',
  AoTPreparePerByte: 'Per byte of contract code, on every call to the contract',
  GetCode:
    'Flat cost of loading the contract code, on every call to the contract',
  // BigIntAPICost
  CopyPerByteForTooBig:
    'Per byte of a big integer longer than 32 bytes, when it is copied or operated on',
  // DynamicStorageLoad
  QuadraticCoefficient: '`a` in `a·d² + b·d + c`',
  LinearCoefficient: '`b` in `a·d² + b·d + c`',
  ConstantCoefficient: '`c` in `a·d² + b·d + c`',
  SignOfQuadratic: 'Sign of `a`: 0 positive, 1 negative',
  SignOfLinear: 'Sign of `b`: 0 positive, 1 negative',
  SignOfConstant: 'Sign of `c`: 0 positive, 1 negative',
  MinimumGasCost:
    "If the curve gives less than this, the read is charged the host function's fixed storage-load cost instead",
  // MaxPerTransaction
  MaxBuiltInCallsPerTx: 'Built-in function calls one transaction may make',
  MaxNumberOfTransfersPerTx: 'Token transfers one transaction may make',
  MaxNumberOfTrieReadsPerTx:
    'Storage reads from the state trie one transaction may make',
  // WASMOpcodeCost entries that are limits or settings, not opcodes
  MaxMemoryGrow: 'Limit, not a cost: `memory.grow` calls allowed in one call',
  MaxMemoryGrowDelta: 'Limit, not a cost: pages one `memory.grow` may request',
  MemoryGrow: 'Flat cost of one `memory.grow`, whatever the size',
  LocalAllocate:
    'Per local variable a function declares beyond `LocalsUnmetered`',
  LocalsUnmetered:
    'Setting, not a cost: locals per function that are not charged',
  MaxDeclaredTableSize: 'Limit, not a cost: largest table a module may declare',
  TableInitPerElement: 'Per element copied by `table.init`',
}

function costTable(s: Map<string, number>, withMeaning = true): string {
  const rows = [...s].map(([k, v]) =>
    withMeaning
      ? [`\`${k}\``, fmt(v), MEANINGS[k] ?? '']
      : [`\`${k}\``, fmt(v)],
  )
  return table(
    withMeaning ? ['Name', 'Cost', 'Meaning'] : ['Name', 'Cost'],
    rows,
  )
}

/** Groups for the WASM opcode table, tried in order; the first match wins. */
const OPCODE_GROUPS: [string, (op: string) => boolean][] = [
  [
    'Limits and settings',
    (op) =>
      /^(MaxMemoryGrow|MaxMemoryGrowDelta|MaxDeclaredTableSize|LocalAllocate|LocalsUnmetered)$/.test(
        op,
      ),
  ],
  [
    'Control flow',
    (op) =>
      /^(Unreachable|Nop|Block|Loop|If|Else|End|Br|BrIf|BrTable|Return|Call|CallIndirect|ReturnCall|ReturnCallIndirect|Drop|Select|TypedSelect|Try|Catch|CatchAll|Throw|Rethrow|Delegate|Unwind)$/.test(
        op,
      ),
  ],
  ['Locals and globals', (op) => /^(Local|Global)(Get|Set|Tee)$/.test(op)],
  [
    'Memory',
    (op) =>
      /^(I32|I64|F32|F64)(Load|Store)/.test(op) ||
      /^(MemorySize|MemoryGrow|MemoryInit|MemoryCopy|MemoryFill|DataDrop)$/.test(
        op,
      ),
  ],
  ['Tables and references', (op) => /^(Table|Elem|Ref)/.test(op)],
  ['Atomics (threads)', (op) => /Atomic/.test(op)],
  [
    'SIMD (128-bit vectors)',
    (op) =>
      /^(V128|V8x16|V16x8|V32x4|V64x2|I8x16|I16x8|I32x4|I64x2|F32x4|F64x2)/.test(
        op,
      ),
  ],
  [
    'Integer arithmetic, comparison and conversion',
    (op) => /^(I32|I64)/.test(op),
  ],
  ['Floating point', (op) => /^(F32|F64)/.test(op)],
]

function opcodeTables(s: Map<string, number>): string {
  const groups = new Map<string, [string, number][]>(
    OPCODE_GROUPS.map(([g]) => [g, []]),
  )
  for (const [op, cost] of s) {
    const group = OPCODE_GROUPS.find(([, match]) => match(op))
    if (!group)
      throw new Error(`opcode ${op} fits no group; add it to OPCODE_GROUPS`)
    groups.get(group[0])!.push([op, cost])
  }
  return [...groups]
    .filter(([, ops]) => ops.length > 0)
    .map(([g, ops]) => {
      const isSettings = g === 'Limits and settings'
      const rows = ops.map(([op, c]) =>
        isSettings
          ? [`\`${op}\``, fmt(c), MEANINGS[op] ?? '']
          : [`\`${op}\``, fmt(c)],
      )
      const body = table(
        isSettings ? ['Name', 'Value', 'Meaning'] : ['Opcode', 'Cost'],
        rows,
      )
      return `<details>\n<summary>${g} (${ops.length})</summary>\n\n${body}\n\n</details>`
    })
    .join('\n\n')
}

export function render(schedule: Schedule, pkg: string, date: string): string {
  const total = (name: string) => section(schedule, name).size
  const known = new Set([
    'BuiltInCost',
    'BaseOperationCost',
    'BaseOpsAPICost',
    'EthAPICost',
    'BigIntAPICost',
    'BigFloatAPICost',
    'ManagedBufferAPICost',
    'ManagedMapAPICost',
    'CryptoAPICost',
    'WASMOpcodeCost',
    'DynamicStorageLoad',
    'MaxPerTransaction',
  ])
  for (const name of schedule.keys()) {
    if (!known.has(name))
      throw new Error(
        `new gas schedule section ${name}: add it to the generator`,
      )
  }

  const api = (name: string, title: string, intro: string) =>
    `### ${title}\n\n${intro}\n\n<details>\n<summary>\`${name}\` (${total(name)} entries)</summary>\n\n${costTable(
      section(schedule, name),
      false,
    )}\n\n</details>`

  return [
    `<Note>`,
    `Values from \`gasScheduleV1.yaml\` in mainnet configuration package ${pkg}, read on ${date}. Testnet runs the same file. They are set by the network configuration, not by the VM code, and a gas schedule update can change them.`,
    `</Note>`,
    '',
    `### Base operations`,
    '',
    `\`BaseOperationCost\`: per-byte charges and code loading.`,
    '',
    costTable(section(schedule, 'BaseOperationCost')),
    '',
    `### Storage reads by trie depth`,
    '',
    `\`DynamicStorageLoad\`: the coefficients of the storage read curve.`,
    '',
    costTable(section(schedule, 'DynamicStorageLoad')),
    '',
    `### Per-transaction limits`,
    '',
    `\`MaxPerTransaction\`: these are counts, not gas.`,
    '',
    table(
      ['Name', 'Limit', 'Meaning'],
      [...section(schedule, 'MaxPerTransaction')].map(([k, v]) => [
        `\`${k}\``,
        fmt(v),
        MEANINGS[k] ?? '',
      ]),
    ),
    '',
    api(
      'BaseOpsAPICost',
      'Host functions: base operations',
      'Arguments, caller, call value, storage, block data, logs, and calls to other contracts.',
    ),
    '',
    api(
      'ManagedBufferAPICost',
      'Host functions: managed buffers',
      'The managed buffer API that the Rust framework uses for most data.',
    ),
    '',
    api(
      'BigIntAPICost',
      'Host functions: big integers',
      'Arbitrary-precision integers (`BigUint`, `BigInt`).',
    ),
    '',
    api(
      'BigFloatAPICost',
      'Host functions: big floats',
      'Arbitrary-precision decimals (`BigFloat`).',
    ),
    '',
    api(
      'ManagedMapAPICost',
      'Host functions: managed maps',
      'Key-value maps held by the VM.',
    ),
    '',
    api(
      'CryptoAPICost',
      'Host functions: cryptography',
      'Hashes and signature checks.',
    ),
    '',
    api(
      'EthAPICost',
      'Host functions: Ethereum-compatible API',
      'The EEI-style API kept for compatibility.',
    ),
    '',
    api(
      'BuiltInCost',
      'Built-in functions',
      'Protocol operations that a contract triggers, such as transfers, freezes and asset creation.',
    ),
    '',
    `### WebAssembly opcodes`,
    '',
    `\`WASMOpcodeCost\`: ${total('WASMOpcodeCost')} entries, grouped by kind. A few entries in this section are limits or settings rather than opcode costs; they are listed first.`,
    '',
    opcodeTables(section(schedule, 'WASMOpcodeCost')),
  ].join('\n')
}

async function main() {
  const [file, pkg, date] = process.argv.slice(2)
  if (!file || !pkg || !/^\d{4}-\d{2}-\d{2}$/.test(date ?? '')) {
    console.error(
      'usage: generate-gas-tables <gasScheduleV1.yaml> <config package number> <YYYY-MM-DD>',
    )
    process.exit(1)
  }
  const generated = render(parseSchedule(readFileSync(file, 'utf8')), pkg, date)
  const page = readFileSync(PAGE, 'utf8')
  const start = page.indexOf(BEGIN)
  const stop = page.indexOf(END)
  if (start < 0 || stop < start) throw new Error(`markers not found in ${PAGE}`)
  const out = `${page.slice(0, start + BEGIN.length)}\n\n${generated}\n\n${page.slice(stop)}`
  // Format like the rest of the repository so re-running the script on the same schedule changes nothing.
  const options = (await prettier.resolveConfig(PAGE)) ?? {}
  writeFileSync(
    PAGE,
    await prettier.format(out, { ...options, filepath: PAGE }),
  )
  console.log(
    `wrote gas tables from ${file} (package ${pkg}, ${date}) into ${PAGE}`,
  )
}

if (require.main === module) {
  main().catch((err) => {
    console.error(err instanceof Error ? err.message : err)
    process.exit(1)
  })
}
